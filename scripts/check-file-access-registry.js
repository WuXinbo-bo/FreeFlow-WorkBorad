const assert = require("assert/strict");
const fs = require("fs");
const os = require("os");
const path = require("path");
const { createFileAccessRegistry, assertFileIpcAccess, isWithinPath } = require("../electron/fileAccessRegistry");
const root = fs.mkdtempSync(path.join(os.tmpdir(), "freeflow-file-access-"));
try {
  const allowed = path.join(root, "selected");
  const outside = path.join(root, "private");
  fs.mkdirSync(allowed); fs.mkdirSync(outside);
  fs.writeFileSync(path.join(outside, "secret"), "private");
  const storagePath = path.join(root, "permissions.json");
  const access = createFileAccessRegistry({ storagePath });
  access.grant(allowed, { directory: true, write: true });
  access.assert(path.join(allowed, "new", "board.freeflow"), { write: true });
  assert.throws(() => access.assert(path.join(allowed, "..", "private", "secret")), /尚未授权/);
  fs.symlinkSync(outside, path.join(allowed, "escape"), "dir");
  assert.throws(() => access.assert(path.join(allowed, "escape", "secret")), /尚未授权/);
  assert.throws(() => access.assert(path.join(allowed, "escape", "new"), { write: true }), /尚未授权/);
  fs.symlinkSync(path.join(outside, "missing"), path.join(allowed, "dangling"));
  assert.throws(() => access.assert(path.join(allowed, "dangling"), { write: true }));
  const selectedFile = path.join(outside, "secret");
  access.grant(selectedFile);
  access.assert(selectedFile);
  assert.throws(() => access.assert(selectedFile, { write: true }), /尚未授权/);
  assert.throws(() => assertFileIpcAccess(access, "desktop-shell:rename-path", [selectedFile, path.join(allowed, "copy")]), /尚未授权/);
  const restored = createFileAccessRegistry({ storagePath });
  restored.assert(selectedFile);
  restored.assert(path.join(allowed, "new.freeflow"), { write: true });
  fs.unlinkSync(path.join(allowed, "escape"));
  fs.mkdirSync(path.join(allowed, "escape"));
  restored.assert(path.join(allowed, "escape", "new.freeflow"), { write: true });
  assert.throws(() => restored.assert("relative.file"), /无效/);
  assert.throws(() => restored.assert(path.join(allowed, "bad\0path")), /无效/);
  assert(isWithinPath("C:\\Boards", "c:\\boards\\new.freeflow", path.win32));
  assert(!isWithinPath("C:\\Boards", "D:\\Boards\\new.freeflow", path.win32));
  assert(!isWithinPath("C:\\Boards", "C:\\BoardsOther\\new.freeflow", path.win32));
  assert(isWithinPath("\\\\server\\share\\Boards", "\\\\server\\share\\Boards\\new.freeflow", path.win32));
  assert(!isWithinPath("\\\\server\\share\\Boards", "\\\\server\\other\\secret", path.win32));
  console.log("[check-file-access-registry] explicit grants, persistence, traversal, symlinks, new files and Windows/UNC boundaries passed");
} finally { fs.rmSync(root, { recursive: true, force: true }); }
