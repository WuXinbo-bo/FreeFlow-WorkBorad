"use strict";
const assert = require("assert/strict");
const fs = require("fs/promises");
const os = require("os");
const path = require("path");
const http = require("http");
const zlib = require("zlib");
const { ExtensionManager, digest } = require("../src/backend/extensions/extensionManager");
const catalog = require("../src/backend/extensions/assistantCatalog.json");
async function main() {
  const temp = await fs.mkdtemp(path.join(os.tmpdir(), "freeflow-extension-"));
  process.env.FREEFLOW_HOME_DIR = temp;
  process.env.FREEFLOW_USER_DATA_DIR = path.join(temp, "AppData");
  process.env.FREEFLOW_LEGACY_PROJECT_DATA_DIR = path.join(temp, "Legacy");
  const bytes = await fs.readFile(path.join(__dirname, "../build/extensions", catalog.filename));
  let runtime;
  let downloadServer;
  try {
    const legacyDir = path.join(temp, "legacy-upgrade");
    await fs.mkdir(legacyDir);
    const legacySettings = '{"schemaVersion":3,"activeProvider":"claude","providers":{}}';
    await fs.writeFile(path.join(legacyDir, "agent-settings.json"), legacySettings);
    const migrated = new ExtensionManager({ dataDir: legacyDir, catalog, localPackage: path.join(__dirname, "../build/extensions", catalog.filename) });
    await migrated.initialize(); assert.equal(migrated.enabled(), true);
    assert.equal(await fs.readFile(path.join(legacyDir, "agent-settings.json"), "utf8"), legacySettings);
    await migrated.change("disable");
    const migratedRestart = new ExtensionManager({ dataDir: legacyDir, catalog });
    await migratedRestart.initialize(); assert.equal(migratedRestart.enabled(), false);
    await migrated.change("uninstall");
    const removedRestart = new ExtensionManager({ dataDir: legacyDir, catalog });
    await removedRestart.initialize(); assert.equal(removedRestart.status().state, "not-installed");
    const onlineLegacyDir = path.join(temp, "legacy-online");
    await fs.mkdir(onlineLegacyDir);
    await fs.writeFile(path.join(onlineLegacyDir, "agent-settings.json"), legacySettings);
    const onlineLegacy = new ExtensionManager({ dataDir: onlineLegacyDir, catalog, download: async () => { throw new Error("offline"); } });
    await onlineLegacy.initialize(); await onlineLegacy.restoreLegacy();
    assert.equal(onlineLegacy.enabled(), false);
    assert.match(onlineLegacy.status().error, /原有 AI 数据已保留/);
    onlineLegacy.download = async () => bytes;
    await onlineLegacy.change("install"); await onlineLegacy.change("enable");
    assert.equal(onlineLegacy.enabled(), true);
    assert.equal(await fs.readFile(path.join(onlineLegacyDir, "agent-settings.json"), "utf8"), legacySettings);
    const { AgentStore } = require("../src/backend/agent/agentStore");
    const future = new AgentStore(path.join(temp, "future.sqlite"));
    future.open(); future.db.exec("PRAGMA user_version=999"); future.close();
    assert.throws(() => future.open(), /更新版本/);
    const fresh = new ExtensionManager({ dataDir: path.join(temp, "fresh"), catalog, download: async () => bytes });
    await fresh.initialize();
    assert.equal(fresh.status().state, "not-installed");
    assert.equal(fresh.enabled(), false);
    await fresh.change("install");
    assert.equal(fresh.status().state, "disabled");
    await fresh.change("enable");
    assert.equal(fresh.enabled(), true);
    await fresh.change("disable");
    assert.equal(fresh.enabled(), false);
    await fresh.change("enable");
    const metadata = await fs.readFile(path.join(fresh.root, "state.json"), "utf8");
    const recreated = new ExtensionManager({ dataDir: path.join(temp, "fresh"), catalog });
    await recreated.initialize(); assert.equal(recreated.enabled(), true);
    fresh.download = async () => Buffer.from("corrupt");
    await assert.rejects(fresh.change("install"), /校验/);
    assert.equal(fresh.enabled(), true);
    assert.equal(await fs.readFile(path.join(fresh.root, "state.json"), "utf8"), metadata);
    await fresh.verifyInstalled();
    await fs.writeFile(path.join(fresh.directory(), "client.js"), "tampered");
    await assert.rejects(fresh.verifyInstalled(), /损坏/);
    fresh.download = async () => bytes;
    await fresh.change("install");
    await fresh.verifyInstalled();
    await fresh.change("uninstall");
    assert.equal(fresh.status().state, "not-installed");
    const manifest = JSON.parse(zlib.gunzipSync(bytes));
    const wrongPlatform = zlib.gzipSync(JSON.stringify({ ...manifest, platform: catalog.platform === "darwin" ? "win32" : "darwin" }));
    const incompatible = new ExtensionManager({ dataDir: path.join(temp, "wrong-platform"), catalog: { ...catalog, sha256: digest(wrongPlatform) }, download: async () => wrongPlatform });
    await incompatible.initialize(); await assert.rejects(incompatible.change("install"), /平台不兼容/);
    manifest.files["../escape"] = manifest.files["client.js"];
    const malicious = zlib.gzipSync(JSON.stringify(manifest));
    const bad = new ExtensionManager({ dataDir: path.join(temp, "malicious"), catalog: { ...catalog, sha256: digest(malicious) }, download: async () => malicious });
    await bad.initialize(); await assert.rejects(bad.change("install"), /列表无效/);
    let aborted = false;
    fresh.download = (signal) => new Promise((_, reject) => signal.addEventListener("abort", () => { aborted = true; reject(new Error("cancelled")); }, { once: true }));
    const cancelling = fresh.change("install");
    while (!fresh.abortController) await new Promise((resolve) => setImmediate(resolve));
    await assert.rejects(fresh.change("enable"), /处理中/);
    fresh.cancel(); await assert.rejects(cancelling, /cancelled/); assert.equal(aborted, true);
    // Actual HTTP transfer through the production reader, with a loopback transport substituted for GitHub.
    downloadServer = http.createServer((_req, res) => { res.setHeader("Content-Length", bytes.length); res.end(bytes); });
    await new Promise((resolve) => downloadServer.listen(0, "127.0.0.1", resolve));
    const fetchOriginal = global.fetch;
    global.fetch = async (_url, options) => {
      const result = await fetchOriginal(`http://127.0.0.1:${downloadServer.address().port}`, options);
      return { ok: result.ok, status: result.status, url: catalog.url, headers: result.headers, body: result.body };
    };
    try { const remote = new ExtensionManager({ dataDir: path.join(temp, "http"), catalog }); await remote.initialize(); await remote.change("install"); await remote.verifyInstalled(); }
    finally { global.fetch = fetchOriginal; }
    // Real backend, worker, SQLite, HTTP proxy and settings; no user's data or model credentials.
    runtime = require("../src/backend");
    const server = await runtime.startServer(0);
    const base = `http://127.0.0.1:${server.address().port}`;
    const call = async (url, action) => fetch(base + url, action ? { method: "POST", headers: { "x-freeflow-extension": "1" } } : {});
    assert.equal((await call("/api/agent/bootstrap")).status, 404);
    assert.equal(runtime.assistantHost.child, null);
    assert.equal((await (await call("/api/settings-center")).json()).sections.ai, undefined);
    const initialHtml = await (await call("/")).text();
    assert(!initialHtml.includes('id="chat-form"')); assert(!initialHtml.includes('data-assistant-enabled="true"'));
    const denied = await fetch(base + "/api/extensions/ai-assistant/install", { method: "POST", headers: { origin: "https://evil.example", "x-freeflow-extension": "1" } });
    assert.equal(denied.status, 403);
    for (const action of ["install", "enable"]) assert.equal((await call(`/api/extensions/ai-assistant/${action}`, action)).status, 200);
    assert.equal(runtime.assistantHost.child, null, "enable must not start assistant worker");
    const settings = await (await call("/api/settings-center")).json();
    assert(settings.sections.ai.agent); assert.equal(runtime.assistantHost.child, null, "common settings must not start a worker");
    const html = await (await call("/")).text(); assert(html.includes('id="chat-form"'));
    const bootstrap = await call("/api/agent/bootstrap");
    const cookie = bootstrap.headers.get("set-cookie").split(";")[0];
    assert.equal(bootstrap.status, 200);
    const sessions = await fetch(base + "/api/agent/sessions", { headers: { cookie } });
    assert.equal(sessions.status, 200, await sessions.text());
    assert(runtime.assistantHost.child);
    const saved = await runtime.assistantHost.settings("POST", { showReasoning: false }); assert.equal(saved.showReasoning, false);
    const originalSecret = require("../src/backend/services/secretStorageService");
    await originalSecret.writeSecret("github-sync:test", "retained-core-secret");
    const connection = await fetch(base + "/api/agent/providers/codex/connection", { method: "PUT", headers: { cookie, "Content-Type": "application/json" }, body: JSON.stringify({ baseUrl: "https://api.openai.com", apiKey: "test-extension-secret", apiKeyAction: "replace" }) });
    assert.equal(connection.status, 200, await connection.text());
    assert.equal(await originalSecret.readSecret("agent-provider:codex:api-key"), "test-extension-secret");
    assert.equal(await originalSecret.readSecret("github-sync:test"), "retained-core-secret");
    const stopRuntime = runtime.extensionManager.stopRuntime;
    runtime.extensionManager.stopRuntime = async () => {
      await stopRuntime();
      assert.equal((await call("/api/agent/bootstrap")).status, 404, "replacement must block worker restart before files are swapped");
    };
    assert.equal((await call("/api/extensions/ai-assistant/install", "install")).status, 200);
    runtime.extensionManager.stopRuntime = stopRuntime;
    assert.equal(runtime.extensionManager.enabled(), true, "replacement must restore the enabled preference");
    assert.equal((await fetch(base + "/api/agent/sessions", { headers: { cookie } })).status, 200);
    const dbPath = path.join(process.env.FREEFLOW_USER_DATA_DIR, "agent-sessions.sqlite");
    const beforeDisable = await fs.stat(dbPath);
    for (let index = 0; index < 3; index++) {
      await call("/api/extensions/ai-assistant/disable", "disable");
      assert.equal(runtime.assistantHost.child, null);
      assert.equal((await call("/api/agent/bootstrap")).status, 404);
      await call("/api/extensions/ai-assistant/enable", "enable");
      const started = await fetch(base + "/api/agent/sessions", { headers: { cookie } }); assert.equal(started.status, 200);
    }
    const activePid = runtime.assistantHost.child.pid;
    runtime.assistantHost.child.kill();
    await new Promise((resolve) => runtime.assistantHost.child?.once("exit", resolve) || resolve());
    assert.equal((await fetch(base + "/api/agent/sessions", { headers: { cookie } })).status, 200);
    assert.notEqual(runtime.assistantHost.child.pid, activePid);
    await call("/api/extensions/ai-assistant/uninstall", "uninstall");
    assert.equal(runtime.assistantHost.child, null);
    assert.equal((await fs.stat(dbPath)).size >= beforeDisable.size, true);
    assert.equal(await originalSecret.readSecret("agent-provider:codex:api-key"), "test-extension-secret");
    assert.equal((await call("/extensions/ai-assistant/client.js")).status, 404);
    console.log("[assistant-extension] install/integrity/cancel/origin/lazy-worker/SQLite/credential-broker/re-enable/crash/uninstall checks passed");
  } finally {
    await runtime?.stopServer();
    if (downloadServer) await new Promise((resolve) => downloadServer.close(resolve));
    await fs.rm(temp, { recursive: true, force: true });
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
